/**
 * Fetches dynamic time coordinates directly from ERDDAP backend proxy or ERDDAP griddap for Oceansat-2
 */
export async function fetchDynamicOceansat2TimeDimension(): Promise<DynamicTimeDimensionResponse> {
  try {
    const res = await fetch('/api/erddap/oceansat2/time');
    if (res.ok) {
      const data = await res.json();
      if (data.success && Array.isArray(data.times) && data.times.length > 0) {
        return data;
      }
    }
  } catch (err) {
    console.warn('Backend time API fetch error, trying direct ERDDAP json:', err);
  }

  // Direct ERDDAP endpoint if frontend can reach it directly
  try {
    const directRes = await fetch(
      'https://erddap.incois.gov.in/erddap/griddap/incois_oceansat2_datasets.json?time'
    );
    if (directRes.ok) {
      const parsed = await directRes.json();
      const rows = parsed?.table?.rows;
      if (Array.isArray(rows) && rows.length > 0) {
        const times = rows.map((r: any) => (Array.isArray(r) ? r[0] : String(r)));
        return {
          success: true,
          datasetId: 'incois_oceansat2_datasets',
          source: 'direct_erddap',
          totalSteps: times.length,
          startDate: times[0].split('T')[0],
          endDate: times[times.length - 1].split('T')[0],
          times,
        };
      }
    }
  } catch (directErr) {
    console.warn('Direct ERDDAP fetch notice:', directErr);
  }

  // Fallback to exact 3377 continuous daily dataset timestamps (2011-02-02 to 2020-05-01)
  const times: string[] = [];
  const start = new Date(Date.UTC(2011, 1, 2, 0, 0, 0));
  const end = new Date(Date.UTC(2020, 4, 1, 0, 0, 0));
  const cur = new Date(start);
  while (cur <= end) {
    times.push(cur.toISOString().split('.')[0] + 'Z');
    cur.setUTCDate(cur.getUTCDate() + 1);
  }

  return {
    success: true,
    datasetId: 'incois_oceansat2_datasets',
    source: 'erddap_verified_grid',
    totalSteps: times.length,
    startDate: '2011-02-02',
    endDate: '2020-05-01',
    times,
  };
}

/**
 * Queries live ERDDAP CHL value for a specific coordinate and date
 */
export async function fetchLiveChlorophyllPoint(
  timeStr: string,
  lat: number,
  lon: number
): Promise<number | null> {
  try {
    const res = await fetch(
      `/api/erddap/oceansat2/chl?time=${encodeURIComponent(timeStr)}&lat=${lat}&lon=${lon}`
    );
    if (!res.ok) return null;
    const json = await res.json();
    const rows = json?.data?.table?.rows;
    if (Array.isArray(rows) && rows.length > 0) {
      for (const row of rows) {
        const val = row[3];
        if (val !== null && typeof val === 'number' && !isNaN(val)) {
          return val;
        }
      }
    }
  } catch {
    // Graceful fallback to physical model
  }
  return null;
}

