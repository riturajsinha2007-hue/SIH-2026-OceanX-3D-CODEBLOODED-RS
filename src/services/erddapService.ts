/**
 * Derives scientific season and monsoon classification for a given date in the North Indian Ocean
 */
export function getOceansat2SeasonLabel(dateStr: string): string {
  const parts = dateStr.split('-');
  const month = parseInt(parts[1] || '1', 10);
  const year = parts[0] || '2013';

  if (month === 12 || month === 1) {
    return `${year} Winter NE Monsoon Bloom`;
  } else if (month === 2) {
    return `${year} Late Winter Arabian Sea Bloom`;
  } else if (month === 3) {
    return `${year} Spring Inter-Monsoon Transition`;
  } else if (month === 4 || month === 5) {
    return `${year} Pre-Monsoon Thermal Stratification`;
  } else if (month === 6) {
    return `${year} SW Monsoon Upwelling Onset`;
  } else if (month === 7 || month === 8) {
    return `${year} Summer Monsoon Coastal Upwelling Peak`;
  } else if (month === 9) {
    return `${year} Late SW Monsoon Plume Dispersion`;
  } else if (month === 10 || month === 11) {
    return `${year} Fall Inter-Monsoon / Post-Monsoon Transition`;
  }
  return `${year} Ocean Color Observation`;
}

