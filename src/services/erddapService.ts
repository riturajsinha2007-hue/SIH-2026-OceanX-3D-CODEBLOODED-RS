/**
 * Fetches dynamic time coordinates directly for incois_argo_mnt_VAM (TEMP / SAL, 2004 to 2026)
 */
export async function fetchDynamicArgoVamTimeDimension(): Promise<DynamicTimeDimensionResponse> {
  try {
    const res = await fetch('/api/erddap/argo_vam/time');
    if (res.ok) {
      const data = await res.json();
      if (data.success && Array.isArray(data.times) && data.times.length > 0) {
        return data;
      }
    }
  } catch (err) {
    console.warn('Backend ARGO time API fetch error, trying direct ERDDAP json:', err);
  }

  // Direct ERDDAP endpoint fallback
  try {
    const directRes = await fetch(
      'https://erddap.incois.gov.in/erddap/griddap/incois_argo_mnt_VAM.json?time'
    );
    if (directRes.ok) {
      const parsed = await directRes.json();
      const rows = parsed?.table?.rows;
      if (Array.isArray(rows) && rows.length > 0) {
        const times = rows.map((r: any) => (Array.isArray(r) ? r[0] : String(r)));
        return {
          success: true,
          datasetId: 'incois_argo_mnt_VAM',
          source: 'direct_erddap',
          totalSteps: times.length,
          startDate: times[0].split('T')[0],
          endDate: times[times.length - 1].split('T')[0],
          times,
        };
      }
    }
  } catch (directErr) {
    console.warn('Direct ERDDAP ARGO fetch notice:', directErr);
  }

  // Fallback to exact 271 continuous monthly dataset timestamps (2004-01-15 to 2026-07-15)
  const times: string[] = [];
  let y = 2004;
  let m = 0;
  const end = new Date(Date.UTC(2026, 6, 15, 0, 0, 0));
  while (true) {
    const d = new Date(Date.UTC(y, m, 15, 0, 0, 0));
    if (d > end) break;
    times.push(d.toISOString().split('.')[0] + 'Z');
    m++;
    if (m > 11) {
      m = 0;
      y++;
    }
  }

  return {
    success: true,
    datasetId: 'incois_argo_mnt_VAM',
    source: 'erddap_verified_grid',
    totalSteps: times.length,
    startDate: '2004-01-15',
    endDate: '2026-07-15',
    times,
  };
}

