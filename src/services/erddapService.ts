/**
 * Fetches fully synchronized sounding profile for an Argo float at a specific date, depth, and variable
 */
export async function fetchArgoFloatLiveProfile(
  platformNumber: string,
  timeStr: string,
  variable: 'TEMP' | 'SAL' | 'CHLA' | 'SSH',
  depth: number,
  lat?: number,
  lon?: number,
  signal?: AbortSignal
): Promise<SynchronizedFloatProfileResponse | null> {
  try {
    const queryParams = new URLSearchParams({
      platformNumber,
      time: timeStr,
      variable,
      depth: String(depth),
    });
    if (typeof lat === 'number') queryParams.set('lat', String(lat));
    if (typeof lon === 'number') queryParams.set('lon', String(lon));

    const res = await fetch(`/api/erddap/argo_floats/profile?${queryParams.toString()}`, { signal });
    if (res.ok) {
      const data = await res.json();
      if (data.success) {
        return data as SynchronizedFloatProfileResponse;
      }
    }
  } catch (err: any) {
    if (err.name !== 'AbortError') {
      console.warn(`[ERDDAP] Failed to fetch live profile for float ${platformNumber}:`, err);
    }
  }
  return null;
}



