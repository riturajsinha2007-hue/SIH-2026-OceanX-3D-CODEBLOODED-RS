  const lonMax = params.lonMax !== undefined ? params.lonMax : (params.lon !== undefined ? Math.min(120, params.lon + 0.25) : 80);

  const timeConstraint = params.timeStr ? `[(${params.timeStr}T00:00:00Z):1:(${params.timeStr}T00:00:00Z)]` : '[(last)]';
